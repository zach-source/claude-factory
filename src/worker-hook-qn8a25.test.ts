import { expect, test } from 'bun:test'
import { BEADS_ACTOR_REASON, denyReason, FACTORY_FROM_REASON, FACTORY_RUN_REASON } from './worker-hook.ts'

const GUARDS = [
  { name: 'BEADS_ACTOR', cmd: 'bd create x', reason: BEADS_ACTOR_REASON },
  { name: 'FACTORY_FROM', cmd: 'factory mail r1 implement x', reason: FACTORY_FROM_REASON },
  { name: 'FACTORY_RUN', cmd: 'factory report run-b 3 approve x', reason: FACTORY_RUN_REASON },
]
const WRITERS = [
  'export',
  'declare',
  'typeset',
  'readonly',
  'local',
  'unset',
  'printf',
  'print',
  'read',
  'mapfile',
  'readarray',
  'getopts',
  'vared',
  'integer',
  'float',
  'private',
  'zparseopts',
  'zstyle',
  'zstat',
  'strftime',
  'sysread',
  'getln',
  'wait',
  'compgen',
  'zformat',
  'zregexparse',
  'sysopen',
  'zsystem',
  'syserror',
  'pcre_match',
  'zgetattr',
  'zlistattr',
  'zpty',
  'zselect',
  'ztie',
  'compadd',
  'zcurses',
  'let',
]
const DENY = (n: string, c: string) => [
  `printf -v ${n} x; ${c}`,
  `printf -v${n} x; ${c}`,
  `builtin printf -v ${n} x; ${c}`,
  `print -v ${n} x; ${c}`,
  `read ${n} <<< x; ${c}`,
  `read -r ${n} < f; ${c}`,
  `read -r a ${n} < f; ${c}`,
  `declare +x ${n}; ${c}`,
  `typeset +x ${n}; ${c}`,
  `export +x ${n}; ${c}`,
  `export -n OTHER ${n}; ${c}`,
  `export -- ${n}; ${c}`,
  `declare -n r=${n}; ${c}`,
  `${n}+=x ${c}`,
  `for ${n} in Manager; do ${c}; done`,
  `select ${n} in Manager; do ${c}; done`,
  `foreach ${n} (Manager) ${c}; end`,
  `for ${n} (Manager) ${c}`,
  `exec {${n}}>/dev/null; ${c}`,
  `: {${n}}>/dev/null; ${c}`,
  `cat {${n}}<f; ${c}`,
  `exec 3>f {${n}}>f; ${c}`,
  `(( ${n} = 5 )); ${c}`,
  `(( x, ${n} = 5 )); ${c}`,
  `(( x,${n}=5 )); ${c}`,
  `(( ${n}++ )); ${c}`,
  `(( ++${n} )); ${c}`,
  `echo $(( ${n} = 5 )); ${c}`,
  `echo $(( x, ${n} = 5 )); ${c}`,
  `echo \${a[${n}=5]}; ${c}`,
  `(( ${n}-=5 )); ${c}`,
  `(( ${n}/=5 )); ${c}`,
  `(( ${n}%=5 )); ${c}`,
  `(( ${n}^=5 )); ${c}`,
  `(( ${n}&=5 )); ${c}`,
  `: "\${x:${n} =1}"; ${c}`,
  `(( ${n} |= 5 )); ${c}`,
  `echo $((${n}-=5)); ${c}`,
  `(( 1, ${n}-=5 )); ${c}`,
  `let ${n}*=5; ${c}`,
  `let 'x ${n} = 5'; ${c}`,
  `let x ${n}-=1; ${c}`,
  `: \${x:${n}=1}; ${c}`,
  `: \${x:0:${n}=2}; ${c}`,
  `: \${x:${n}-=1}; ${c}`,
  `[[ 1 -eq ${n}-=1 ]]; ${c}`,
  `echo \${${n}:=x}; ${c}`,
  `echo \${!${n}}; ${c}`,
  `zmodload zsh/x; zfoo ${n}; ${c}`,
  `zle -U ${n}; ${c}`,
  `test 1 -eq ${n}; ${c}`,
  `command grep ${n} f; ${c}`,
  `coproc ${n} { grep x; }; ${c}`,
  `env -u ${n} grep x; ${c}`,
  `X=1 read ${n}; ${c}`,
  `if true; then read ${n}; fi; ${c}`,
  `printf -v '${n}' x; ${c}`,
  `MY_${n}=1 ${c}`,
  `grep -n x <<< "$((${n}=1))"; ${c}`,
  `git log -S x {${n}}>f; ${c}`,
  `for f in a ${n}; do echo; done; ${c}`,
  `echo {${n}} > f; ${c}`,
  ...WRITERS.map(w => `${w} ${n}; ${c}`),
]
const ALLOW = (n: string, c: string) => [
  `printf %s "$${n}"`,
  `printf -v OTHER x; ${c}`,
  `read -r line < f; ${c}`,
  `export X=$${n}`,
  `export X=\${${n}}`,
  `echo ${n}_LOG=1; ${c}`,
  `grep -rn ${n} src`,
  `git commit -m "fix ${n} guard"`,
  'find . -print',
  `for f in a b; do grep -n ${n} "$f"; done`,
  `git commit -m "fix for ${n}"`,
  `for f (a) grep -n ${n} x`,
  `echo ${n}-x`,
  `(( x + 1 )); grep -n ${n} f`,
  `echo \${a[$${n}]}`,
  `rg ${n} src`,
  `git log -S ${n} --oneline`,
  `bd search '${n}'`,
  `factory memory search 'env guard ${n}'`,
  `env | grep ${n}`,
  `if grep -q ${n} f; then echo y; fi`,
  `echo MY_${n}`,
  `echo \${${n}}`,
  `grep ${n}_LOG f`,
]

for (const g of GUARDS) {
  test(`${g.name}: variable writers deny`, () => {
    for (const cmd of DENY(g.name, g.cmd)) expect([cmd, denyReason(cmd)]).toEqual([cmd, g.reason])
  })
  test(`${g.name}: reads and unrelated text allow`, () => {
    for (const cmd of ALLOW(g.name, g.cmd)) expect([cmd, denyReason(cmd)]).toEqual([cmd, undefined])
  })
}
